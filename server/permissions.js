export function can(role, permission) {
  return Boolean(permissionMatrix[role]?.[permission]);
}

export function requirePermission(role, permission) {
  if (!can(role, permission)) {
    const error = new Error(`Role ${role || "unknown"} cannot ${permission}.`);
    error.status = 403;
    error.code = "FORBIDDEN";
    throw error;
  }
}
